function showCoin(c) {
  const det = document.getElementById("coin-detail");
  const metalIcon = /золот/i.test(c.m) ? "✨" : /серебр/i.test(c.m) ? "⚪" : "🟤";
  det.innerHTML =
    `<button class="cd-close">✕</button>` +
    `${(window.adminIsOn && window.adminIsOn()) ? `<button class="cd-edit-btn" onclick="window.__adminEditCoinById('${escA(c._id || "")}')">✎ Править</button>` : ""}` +
    `<div class="cd-metal-badge">${metalIcon} ${c.m}</div>` +
    `<h3 class="cd-title">${c.n}</h3>` +
    `<div class="cd-sub">${c.y}</div>` +
    `<div class="cd-imgs" id="cd-imgs"><div class="cd-photo skel"></div></div>` +
    `<table>` +
    `<tr><td>Годы</td><td>${c.y}</td></tr>` +
    `<tr><td>Металл</td><td>${c.m}</td></tr>` +
    `<tr><td>Вес</td><td>${c.w}</td></tr>` +
    `<tr><td>Размер</td><td>${c.s}</td></tr>` +
    `<tr><td>Редкость</td><td><span class="rare-${c.r}">${RARE[c.r]}</span></td></tr>` +
    `</table>` +
    `<div class="cd-desc"><p>${c.d}</p></div>`;
  det.classList.remove("hidden");
  det.scrollTop = 0;
  det.querySelector(".cd-close").onclick = () => det.classList.add("hidden");

  // Метка текущей карточки: если пока грузились фото, открыли другую монету —
  // не вливаем старые картинки в новую карточку
  const coinToken = c.g + "|" + c.n + "|" + c.y;
  det.dataset.coin = coinToken;

  loadCoinImages(c).then(imgs => {
    if (det.dataset.coin !== coinToken) return;
    const box = document.getElementById("cd-imgs");
    if (!box) return;
    if (imgs && imgs.length) {
      box.innerHTML = imgs.map(im =>
        `<div class="cd-photo"><img class="cd-img" src="${escA(im.t)}" data-full="${escA(im.f)}" alt="монета"></div>`
      ).join("") +
      `<div class="cd-caption">Фото: Википедия / Wikimedia Commons · тап — на весь экран</div>`;
      box.querySelectorAll(".cd-img").forEach(img => {
        img.onload = () => img.classList.add("show");
        img.onclick = (e) => { e.stopPropagation(); openLightbox(img.dataset.full); };
      });
    } else {
      const gu = (GROUPS.find(x => x.id === c.g) || {}).u || "";
      box.innerHTML = `<div class="cd-noimg">🪙 Фото не нашлось — открой <a class="gh-link" href="${escA(gu)}" target="_blank">uCoin ↗</a></div>`;
    }
  });
}

