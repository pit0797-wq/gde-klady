// Экранирование значений для HTML-атрибутов (URL с кавычками ломали разметку)
const escA = t => String(t ?? "")
  .replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

// ===== ПОРТРЕТЫ ПРАВИТЕЛЕЙ ИЗ ВИКИПЕДИИ =====
const portraits = {};

function fetchPortrait(wiki) {
  // Кэшируем промис: параллельный вызов дождётся того же запроса и не потеряет портрет
  if (portraits[wiki]) return portraits[wiki];
  portraits[wiki] = fetch("https://ru.wikipedia.org/api/rest_v1/page/summary/" + encodeURIComponent(wiki))
    .then(r => r.json())
    .then(d => (d && d.thumbnail && d.thumbnail.source) ? d.thumbnail.source : null)
    .catch(() => null);
  return portraits[wiki];
}

// ===== ФОТО МОНЕТ: КАНОНИЧНЫЕ + МАКСИМАЛЬНОЕ ПОКРЫТИЕ =====
// L1: прямая ссылка (c.img), если задана вручную.
// L2: статьи Википедии о номинале (список запасных — для чешуек и мелочи).
// L3: поиск по Commons: основной запрос, английский, запасной.
// L4: честная заглушка со ссылкой на uCoin. Случайных фото нет.

const imgCache = {};
const THUMB = 480;

// fetch с кэшем в localStorage: повторные визиты почти без сети
function cachedFetch(url, key) {
  const k = "imgcache:" + key;
  try {
    const raw = localStorage.getItem(k);
    if (raw) {
      const box = JSON.parse(raw);
      if (Date.now() - box.ts < 7 * 24 * 3600 * 1000) return Promise.resolve(box.d);
    }
  } catch (e) {}
  return fetch(url).then(r => r.json()).then(d => {
    try { localStorage.setItem(k, JSON.stringify({ d: d, ts: Date.now() })); } catch (e) {}
    return d;
  }).catch(() => null);
}

// ИСПРАВЛЕНО: размер меняем только в последнем сегменте пути.
// Прежняя регулярка ломала ссылки, где «число px-» встречалось в имени файла.
function upscaleThumb(src) {
  if (!src) return src;
  return src.replace(/\/\d+px-([^\/]+)$/, "/" + THUMB + "px-$1");
}

// Статьи Википедии для номинала. Только реально существующие имена;
// цепочка пробуется по очереди, при пустоте уходит в поиск по Commons.
function wikiArticlesFor(c) {
  if (c.wp) return [c.wp];
  const n = c.n.toLowerCase();
  if (n.includes("сребреник")) return ["Сребреник"];
  if (n.includes("гривна")) return ["Гривна"];
  if (n.includes("дирхем")) return ["Дирхам"];
  if (n.includes("пул")) return ["Пул (монета)"];
  if (n.includes("ефимок")) return ["Ефимок"];
  if (n.includes("чешуйка")) return ["Проволочные деньги", "Копейка (монета)"];
  if (n.includes("полтина") || n.includes("полтинник") || n.includes("50 копеек")) return ["Полтина"];
  if (n.includes("¼ копейки") || n.includes("четверть копейки") ||
      n.includes("½ копейки") || n.includes("полкопейки") || n.includes("полушка"))
    return ["Полушка", "Копейка (монета)"];
  if (n.includes("денежка") || n.includes("денга")) return ["Денга", "Копейка (монета)"];
  if (n.includes("5 копеек")) return ["Пятак"];
  if (n.includes("25 копеек")) return ["Полуполтинник"];
  if (n.includes("гривенник") || n.includes("10 копеек")) return ["Гривенник"];
  if (n.includes("20 копеек")) return ["Двугривенный", "Гривенник"];
  if (n.includes("копейка")) return ["Копейка (монета)"];
  if (n.includes("алтынник")) return ["Алтын"];
  if (n.includes("юбилей") || n.includes("памятн")) return ["Юбилейные монеты СССР", "Юбилейные монеты России"];
  if (n.includes("биметалл")) return ["Юбилейные монеты России", "Юбилейные монеты СССР"];
  if (n.includes("рубль")) return ["Рубль (монета)", "Рубль"];
  return [];
}

// Фото статьи: миниатюра для списков + оригинал для зума
function fetchWikiImage(article) {
  const key = "wp:" + article;
  if (imgCache[key] !== undefined) return Promise.resolve(imgCache[key]);
  const url = "https://ru.wikipedia.org/api/rest_v1/page/summary/" + encodeURIComponent(article);
  return cachedFetch(url, key).then(d => {
    let out = [];
    if (d && d.thumbnail && d.thumbnail.source) {
      const full = (d.originalimage && d.originalimage.source) ? d.originalimage.source : d.thumbnail.source;
      out = [{ t: upscaleThumb(d.thumbnail.source), f: full }];
    }
    imgCache[key] = out;
    return out;
  });
}

// Пробуем статьи по очереди: где-то точно есть фото
function tryWikiArticles(articles) {
  let chain = Promise.resolve([]);
  articles.forEach(a => {
    chain = chain.then(prev => (prev && prev.length) ? prev : fetchWikiImage(a));
  });
  return chain;
}

// Уточнённый поиск по Commons: сервер сам отдаёт готовую миниатюру 480 px
function commonsQuery(q) {
  if (!q) return Promise.resolve([]);
  const key = "cm:" + q;
  const url = "https://commons.wikimedia.org/w/api.php?action=query" +
    "&generator=search&gsrnamespace=6&gsrlimit=8" +
    "&prop=imageinfo&iiprop=url|mime&iiurlwidth=" + THUMB + "&format=json&origin=*" +
    "&gsrsearch=" + encodeURIComponent(q + " coin obverse");
  return cachedFetch(url, key).then(d => {
    const pages = (d && d.query && d.query.pages) ? Object.values(d.query.pages) : [];
    return pages
      .map(p => (p.imageinfo && p.imageinfo[0]) || null)
      .filter(i => i && /jpe?g|png/i.test(i.mime || ""))
      .map(i => ({ t: i.thumburl, f: i.url }))
      .slice(0, 2);
  }).catch(() => []);
}

// ===== Очередь загрузок: 2 параллельных запроса — быстрее и без шторма =====
const imgQueue = [];
let running = 0;
const MAX_PARALLEL = 2;

function enqueueImg(coin, cb) {
  imgQueue.push([coin, cb]);
  pumpQueue();
}
function pumpQueue() {
  while (running < MAX_PARALLEL && imgQueue.length) {
    running++;
    const pair = imgQueue.shift();
    let p;
    try { p = loadCoinImages(pair[0]); }
    catch (e) { p = Promise.resolve([]); }
    p.then(imgs => pair[1](imgs))
      .catch(() => pair[1]([]))
      .then(() => { running--; pumpQueue(); });
  }
}

function loadCoinImages(c) {
  if (c._imgs) return Promise.resolve(c._imgs);

  const tryCommons = () =>
    commonsQuery((c.q || c.n))
      .then(a => (a && a.length) ? a : commonsQuery(c.q2))
      .then(a => (a && a.length) ? a : commonsQuery((c.qEn || (c.q || c.n)).replace(/копеек/gi, "kopek")));

  const p = (c.img) ? Promise.resolve([{ t: c.img, f: c.img }])
    : tryWikiArticles(wikiArticlesFor(c))
        .then(a => (a && a.length) ? a : tryCommons());

  return p.then(imgs => {
    // Пустой результат (сбой сети) не кэшируем — попробуем снова при следующем показе
    if (imgs && imgs.length) c._imgs = imgs;
    return imgs || [];
  });
}

// ===== Ленивая загрузка превью: только видимые карточки =====
const thumbObserver = new IntersectionObserver((entries, obs) => {
  entries.forEach(en => {
    if (!en.isIntersecting) return;
    const el = en.target;
    obs.unobserve(el);
    const c = el.__coin;
    if (!c) return;
    enqueueImg(c, imgs => {
      if (!el.isConnected) return; // карточку уже перерисовали
      if (imgs && imgs.length) {
        el.innerHTML = `<img src="${escA(imgs[0].t)}" alt="">`;
        el.classList.remove("skel");
        el.classList.add("loaded");
      } else {
        el.classList.remove("skel");
        el.classList.add("noimg");
        el.textContent = "🪙";
      }
    });
  });
}, { rootMargin: "260px 0px" });

function thumbFor(c) {
  const d = document.createElement("div");
  d.className = "coin-thumb skel";
  d.textContent = "🪙";
  d.__coin = c;
  thumbObserver.observe(d);
  return d;
}

